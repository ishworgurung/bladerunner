package main

import (
	"errors"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"text/template"
)

// unitTemplate is the systemd service. The ordering lines are the point of it:
// the filter is started BEFORE network-pre.target, so it is attached before the
// network comes up, and Type=notify means systemd treats it as started only once
// bladerunner has attached XDP (it sends READY=1 at that moment).
const unitTemplate = `# Generated by: bladerunner systemd{{.Args}}
[Unit]
Description=bladerunner XDP DDoS filter
Documentation=https://github.com/ishworgurung/bladerunner
# Start before the network is configured, so there is no window at boot with no filter.
DefaultDependencies=no
Wants=network-pre.target
Before=network-pre.target shutdown.target
After=systemd-modules-load.service systemd-udevd.service local-fs.target
Conflicts=shutdown.target
RequiresMountsFor=/sys/fs/bpf {{.StateDir}}
# Do nothing, rather than fail the boot, on a host that has no config yet.
ConditionPathExists={{.Config}}

[Service]
# Ready only once XDP is attached (bladerunner sends READY=1 to systemd).
Type=notify
NotifyAccess=main
# Clear pins left by a crash, so the restart is not refused as "another instance is active".
ExecStartPre=-{{.Bin}} detach --pin {{.Pin}}
# If the config is broken, start from the last copy that worked (see --last-good).
ExecStart={{.Bin}} run -c {{.Config}} --last-good {{.StateDir}}/last-good.yaml --wait-iface {{.WaitIface}}
ExecReload=/bin/kill -HUP $MAINPID
Restart=on-failure
RestartSec=2
TimeoutStartSec=90
# Holds last-known-good config; created by systemd, root only.
StateDirectory=bladerunner
StateDirectoryMode=0750
# Older kernels count BPF memory against RLIMIT_MEMLOCK.
LimitMEMLOCK=infinity
# Hardening that leaves what XDP attach and pinning need.
NoNewPrivileges=yes
PrivateTmp=yes
ProtectHome=yes
ProtectSystem=strict
ReadWritePaths=/sys/fs/bpf
ProtectKernelModules=yes
ProtectControlGroups=yes
RestrictRealtime=yes
LockPersonality=yes

[Install]
WantedBy=multi-user.target
`

type unitData struct {
	Args, Bin, Config, Pin, StateDir, WaitIface string
}

// renderUnit fills in the template. Values go straight into a unit file, so
// anything that systemd would need to quote or expand is refused.
func renderUnit(d unitData) (string, error) {
	for name, v := range map[string]string{"--bin": d.Bin, "--config": d.Config, "--pin": d.Pin, "--state-dir": d.StateDir} {
		if !filepath.IsAbs(v) {
			return "", fmt.Errorf("%s must be an absolute path, got %q", name, v)
		}
		if strings.ContainsAny(v, " \t\n\"'\\%$;") {
			return "", fmt.Errorf("%s must not contain spaces or special characters, got %q", name, v)
		}
	}
	var b strings.Builder
	if err := template.Must(template.New("unit").Parse(unitTemplate)).Execute(&b, d); err != nil {
		return "", err
	}
	return b.String(), nil
}

// cmdSystemd prints a systemd unit for this machine, or installs it.
func cmdSystemd(args []string) error {
	fs := flag.NewFlagSet("systemd", flag.ExitOnError)
	bin := fs.String("bin", "/usr/local/bin/bladerunner", "absolute path of the bladerunner binary on the target host")
	cfg := fs.String("config", "/etc/bladerunner/bladerunner.yaml", "config file the service runs with")
	pin := fs.String("pin", defaultPin, "bpffs pin directory (must match pin_dir in the config)")
	state := fs.String("state-dir", "/var/lib/bladerunner", "directory for the last known-good config (matches StateDirectory=bladerunner)")
	wait := fs.String("wait-iface", "30s", "how long the service waits for the interface to appear at boot")
	install := fs.Bool("install", false, "write the unit to --unit-dir instead of printing it (needs root)")
	unitDir := fs.String("unit-dir", "/etc/systemd/system", "where --install writes bladerunner.service")
	force := fs.Bool("force", false, "overwrite an existing unit with --install")
	fs.Parse(args)

	if !strings.HasPrefix(*state, "/var/lib/") {
		return errors.New("--state-dir must be under /var/lib/ (it is created through StateDirectory=)")
	}
	var passed []string
	fs.Visit(func(f *flag.Flag) {
		if f.Name != "install" && f.Name != "force" && f.Name != "unit-dir" {
			passed = append(passed, fmt.Sprintf("--%s %s", f.Name, f.Value))
		}
	})
	a := ""
	if len(passed) > 0 {
		a = " " + strings.Join(passed, " ")
	}
	out, err := renderUnit(unitData{Args: a, Bin: *bin, Config: *cfg, Pin: *pin, StateDir: *state, WaitIface: *wait})
	if err != nil {
		return err
	}
	if !*install {
		fmt.Print(out)
		return nil
	}
	path := filepath.Join(*unitDir, "bladerunner.service")
	flags := os.O_WRONLY | os.O_CREATE | os.O_EXCL
	if *force {
		flags = os.O_WRONLY | os.O_CREATE | os.O_TRUNC
	}
	f, err := os.OpenFile(path, flags, 0o644)
	if err != nil {
		if errors.Is(err, os.ErrExist) {
			return fmt.Errorf("%s exists; use --force to overwrite", path)
		}
		return err
	}
	if _, err := f.WriteString(out); err != nil {
		f.Close()
		return err
	}
	if err := f.Close(); err != nil {
		return err
	}
	fmt.Fprintf(os.Stderr, "wrote %s\nnext:\n  sudo systemctl daemon-reload\n  sudo systemctl enable --now bladerunner\n"+
		"The config must exist at %s first (the unit does nothing without it).\n", path, *cfg)
	return nil
}
